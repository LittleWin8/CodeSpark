export function getArticleById(id) {
  return articles.find((item) => item.id === id) || null
}

export function getRelatedArticles(current, size = 3) {
  if (!current) return articles.slice(0, size)
  const sameTag = articles.filter(
    (item) => item.id !== current.id && item.tags.some((tag) => current.tags.includes(tag))
  )
  const others = articles.filter((item) => item.id !== current.id && !sameTag.includes(item))
  return [...sameTag, ...others].slice(0, size)
}
